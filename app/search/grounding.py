"""Проверка цитируемости: числовой guard + порог близости.

Для основного (экстрактивного) режима эта проверка не нужна — там цитата
дословна по построению. Модуль нужен для двух мест:

1. creative-режим (LLM-обёртка над найденными чанками) — здесь гарантия
   цитатности держится проверкой, а не промптом.
2. Валидация того, что показанный фрагмент действительно отвечает на вопрос:
   если предложение-победитель не содержит ни одного смыслового совпадения
   с запросом по числам, ответ помечается как «низкая уверенность».

Почему не только substring и не только cosine
---------------------------------------------
Чистая подстрока валит честные ответы: LLM перепишет «не позднее 5 рабочих
дней» в «в течение пяти рабочих дней», и формально это уже не подстрока.
Чистый cosine с порогом 0.90 на rubert-tiny2 тоже слишком строг: перефраз
даёт 0.82–0.90, и creative-режим будет падать в fallback на честных ответах.

Поэтому три независимых условия, и числовой — главный:
  - совпадение чисел обязательно, если числа в ответе есть: это ловит
    основной класс галлюцинаций (выдуманный срок, сумма, процент)
    детерминированно, без порогов и без модели;
  - подстрока после агрессивной нормализации — быстрый путь;
  - cosine — для перефразов, с порогом, калибруемым на парах.

Стоимость: ~0.1 мс на предложение (нормализация + поиск чисел). RAM: 0.
"""

from __future__ import annotations

import re
import unicodedata

# Числа: целые, десятичные с точкой или запятой, с разрядами через пробел/неразрывный.
# «1 000 000», «100 000,50», «5», «2.3»
_NUM_RE = re.compile(r"\d+(?:[ \u00a0\u202f]\d{3})*(?:[.,]\d+)?")

# Числа по-русски словами — для числового guard их переводим, иначе
# «пять рабочих дней» и «5 рабочих дней» формально разойдутся.
#
# ВАЖНО: в тексте числа почти всегда стоят в косвенном падеже («в течение
# ПЯТИ рабочих дней», «до ДЕСЯТИ дней», «о ДВУХ этапах»). Поэтому ключи —
# СТЕММЫ (основа без окончания), а не словарные формы: «пят» покрывает
# пять/пяти/пятью, «десят» — десять/десяти/десятью. Иначе guard ложно
# отвергнет честный перефраз, а это ровно тот класс ошибок, который
# в creative-режиме выглядит как поломка.
#
# Порядок в regex — по убыванию длины стемма, чтобы «семнадцат» не был
# съеден «сем».
_NUM_STEMS = {
    "нол": 0, "один": 1, "одн": 1, "дв": 2, "двух": 2, "тр": 3, "трех": 3,
    "четыр": 4, "пят": 5, "шест": 6, "сем": 7, "восем": 8, "девят": 9,
    "десят": 10, "одиннадцат": 11, "двенадцат": 12, "тринадцат": 13,
    "четырнадцат": 14, "пятнадцат": 15, "шестнадцат": 16, "семнадцат": 17,
    "восемнадцат": 18, "девятнадцат": 19, "двадцат": 20, "тридцат": 30,
    "сорок": 40, "пятьдесят": 50, "пятдесят": 50, "шестьдесят": 60,
    "шестдесят": 60, "семьдесят": 70, "восемьдесят": 80, "девяност": 90,
    "ст": 100, "двест": 200, "трист": 300, "четырест": 400, "пятьсот": 500,
    "шестьсот": 600, "семьсот": 700, "восемьсот": 800, "девятьсот": 900,
}
_WORD_NUM_RE = re.compile(
    r"\b(?:" + "|".join(sorted(_NUM_STEMS, key=len, reverse=True)) + r")[а-яё]{0,4}\b",
    re.IGNORECASE,
)

# Символы, которые нормализуем перед сравнением подстроки.
_PUNCT_MAP = str.maketrans({
    "«": '"', "»": '"', "„": '"', "“": '"', "”": '"',
    "—": "-", "–": "-", "−": "-", "‑": "-",
    "\u00a0": " ", "\u202f": " ",
})


def normalize(text: str) -> str:
    """Агрессивная нормализация для сравнения подстрок.

    lower, унификация кавычек/тире/пробелов, снятие диакритики,
    схлопывание пробелов, ё -> е.
    """
    if not text:
        return ""
    s = unicodedata.normalize("NFKC", text).translate(_PUNCT_MAP).lower()
    s = s.replace("ё", "е")
    s = re.sub(r"\s+", " ", s)
    return s.strip(" .;:,")


def _canon_number(raw_digits: str) -> str:
    """Канонизирует число: '100000.50' -> '100000.5', '5.0' -> '5'.

    Нельзя использовать f'{v:g}': формат g по умолчанию даёт 6 значащих цифр
    и превращает 100000.5 в '100000', теряя дробную часть. Это ломало
    числовой guard на суммах с копейками.
    """
    try:
        val = float(raw_digits)
    except ValueError:
        return raw_digits
    if val.is_integer():
        return str(int(val))
    # repr(float) в Python 3 даёт кратчайшее точное представление
    return repr(val).rstrip("0").rstrip(".")


def extract_numbers(text: str) -> set[str]:
    """Множество чисел из текста в каноническом виде.

    «1 000 000», «1000000», «1000 000» -> '1000000'
    «5» -> '5';  «пяти» -> '5';  «2,5» -> '2.5'; «100 000,50» -> '100000.5'
    «миллиона» -> '1000000';  «полтора миллиона» -> '1500000'
    «тысяч» -> '1000';  «пяти тысяч» -> '5000'

    Множители (тысяча/миллион/миллиард) обязательны: в корпоративных
    вопросах сумму почти всегда называют словом («свыше миллиона»), а в
    документе она записана цифрами («свыше 1 000 000 руб.»). Без этого
    совпадение чисел не находится, и поиск отвечает по пункту с другой суммой.
    """
    if not text:
        return set()
    s = normalize(text)
    out: set[str] = set()

    for m in _NUM_RE.finditer(s):
        raw = m.group(0).replace(" ", "").replace("\u00a0", "")
        raw = raw.replace(",", ".").rstrip(".")
        if not raw or raw == ".":
            continue
        out.add(_canon_number(raw))

    for m in _WORD_NUM_RE.finditer(s):
        word = m.group(0).lower()
        for stem in sorted(_NUM_STEMS, key=len, reverse=True):
            if word.startswith(stem):
                out.add(str(_NUM_STEMS[stem]))
                break

    # --- множители: «миллиона», «тысяч», «млрд» ---
    #
    # Порядок важен и был источником бага. Нельзя сначала добавить базовое
    # число, а потом множитель: «до ста тысяч» давало {100, 1000, 100000}
    # вместо {100000}, и признак совпадения чисел становился бесполезным.
    #
    # Поэтому: если число (цифрой или словом) стоит ПЕРЕД множителем,
    # базовое число не добавляется — только произведение.
    # Если множитель стоит один («свыше миллиона»), берётся сам множитель.
    consumed: set[str] = set()

    for mult_re, mult in (
        (r"(?:миллиард\w*|млрд)", 1_000_000_000),
        (r"(?:миллион\w*|млн)", 1_000_000),
        (r"(?:тысяч\w*|тыс\.?)", 1_000),
    ):
        # число цифрой перед множителем: «1 000 000 тысяч» маловероятно,
        # но «1,5 миллиона» — обычное дело
        for mm in re.finditer(rf"(\d+(?:[.,]\d+)?)\s*{mult_re}", s):
            try:
                base = float(mm.group(1).replace(",", "."))
            except ValueError:
                continue
            consumed.add(_canon_number(mm.group(1).replace(",", ".")))
            out.add(_canon_number(str(base * mult)))

        # слово-число перед множителем: «пяти тысяч», «двух миллионов»
        for mm in re.finditer(rf"\b([а-яё]+)\s+{mult_re}", s):
            word = mm.group(1)
            for stem in sorted(_NUM_STEMS, key=len, reverse=True):
                if word.startswith(stem):
                    consumed.add(str(_NUM_STEMS[stem]))
                    out.add(_canon_number(str(_NUM_STEMS[stem] * mult)))
                    break

        # «Голый» множитель («свыше миллиона» -> 1000000) добавляем ТОЛЬКО
        # если перед ним нет числа. Иначе «до ста тысяч» давало лишнее 1000:
        # множитель засчитывался как самостоятельная сумма, хотя он относится
        # к слову «ста». Из-за этого пункты 3.1 и 3.3 становились неразличимы
        # по числам, и цитата выбиралась неверно.
        # Ищем слово непосредственно перед множителем и проверяем,
        # числительное ли оно. «свыше миллиона» -> перед множителем «свыше»,
        # это не числительное, значит голый множитель засчитываем.
        # «до ста тысяч» -> «ста» есть в _NUM_STEMS, значит уже учтено.
        has_number_before = False
        for mm in re.finditer(rf"(\S+)\s+{mult_re}", s):
            prev = mm.group(1).strip(".,;:()")
            if prev.isdigit():
                has_number_before = True
                break
            for stem in _NUM_STEMS:
                if prev.startswith(stem):
                    has_number_before = True
                    break
            if has_number_before:
                break
        if not has_number_before and re.search(mult_re, s):
            out.add(str(mult))

    # Убираем базовые числа, поглощённые множителем.
    out -= consumed

    return out


def extract_numbers_spans(text: str) -> list[tuple[str, int, int]]:
    """Числа с позициями в нормализованном тексте: [(value, start, end)].

    Нужна для определения ГРАНИЦ суммы («до X», «от X», «свыше X»).
    Обычный extract_numbers возвращает только множество значений, и по нему
    нельзя понять, к какому именно числу относится предлог.

    Почему это важно: в запросе «договоры до ста тысяч» число записано
    СЛОВОМ, а не цифрой. Если искать границы только по цифрам, запрос
    не даёт ни одной границы, и пункты «до 100 000» и «от 100 000 до
    1 000 000» становятся неразличимы — оба содержат 100000.

    Позиции возвращаются в нормализованной строке (normalize), потому что
    именно по ней считаются границы; для сравнения с направлением этого
    достаточно.
    """
    if not text:
        return []
    s = normalize(text)
    spans: list[tuple[str, int, int]] = []

    for m in _NUM_RE.finditer(s):
        raw = m.group(0).replace(" ", "").replace("\u00a0", "").replace(",", ".").rstrip(".")
        if not raw or raw == ".":
            continue
        spans.append((_canon_number(raw), m.start(), m.end()))

    # слово-числительное; берём самое длинное совпадение стемма
    for m in _WORD_NUM_RE.finditer(s):
        word = m.group(0).lower()
        for stem in sorted(_NUM_STEMS, key=len, reverse=True):
            if word.startswith(stem):
                spans.append((str(_NUM_STEMS[stem]), m.start(), m.end()))
                break

    # множители: «миллиона» умножает предшествующее число
    for mult_re, mult in (
        (r"(?:миллиард\w*|млрд)", 1_000_000_000),
        (r"(?:миллион\w*|млн)", 1_000_000),
        (r"(?:тысяч\w*|тыс\.?)", 1_000),
    ):
        for mm in re.finditer(mult_re, s):
            # ищем ближайшее число непосредственно перед множителем
            best = None
            for val, st, en in spans:
                if en <= mm.start() and mm.start() - en <= 3:
                    if best is None or en > best[2]:
                        best = (val, st, en)
            if best is not None:
                try:
                    base = float(best[0])
                except ValueError:
                    continue
                spans = [sp for sp in spans if sp[1] != best[1]]
                spans.append((_canon_number(str(base * mult)), best[1], mm.end()))

    spans.sort(key=lambda x: x[1])
    return spans


def numbers_grounded(answer_sentence: str, chunk_text: str) -> bool:
    """Все числа из ответа присутствуют в чанке.

    Ключевое условие creative-режима: выдуманное число — это худший класс
    галлюцинации (неверный срок, сумма, процент), и он ловится
    детерминированно. Если в ответе чисел нет, ограничение не применяется.
    """
    a_nums = extract_numbers(answer_sentence)
    if not a_nums:
        return True
    c_nums = extract_numbers(chunk_text)
    return a_nums.issubset(c_nums)


def substring_grounded(answer_sentence: str, chunk_text: str) -> bool:
    """Предложение ответа — подстрока чанка после агрессивной нормализации."""
    a, c = normalize(answer_sentence), normalize(chunk_text)
    if not a:
        return False
    return a in c


def grounded(
    answer_sentence: str,
    chunk_text: str,
    sim: float,
    thresholds,
) -> tuple[bool, str]:
    """Итоговое решение о цитируемости предложения.

    Возвращает (ok, reason). reason — для логов и отладки, не для пользователя.

    Порядок проверок:
      1. Числа. Провал — сразу False, независимо от sim. Выдуманное число
         не оправдывается высокой косинусной близостью.
      2. Подстрока. Успех — True, быстрый путь, самая сильная гарантия.
      3. Косинус против порога. Порог калибруется на парах
         «перефраз ↔ оригинал»; стартовое значение 0.86, не 0.90.
    """
    if not numbers_grounded(answer_sentence, chunk_text):
        return False, "number_not_grounded"
    if substring_grounded(answer_sentence, chunk_text):
        return True, "substring"
    if sim >= thresholds.creative_min_sim:
        return True, "cosine"
    return False, "low_similarity"