"""Нечёткое сопоставление токенов: опечатки не должны обнулять покрытие.

ДЕФЕКТ, найденный на живом тесте. Вопрос «за сколько ПА обязан принять
заяву» (опечатка: «заяву» вместо «заявку») получал отказ, хотя тот же
вопрос с правильным написанием отвечал п. 5.1:

    заяву:  p=0.63  token_coverage=0.00  -> отказ
    заявку: p=0.73  token_coverage=0.20  -> ответ

Опечатка в одном слове обнуляла покрытие, гейт резал ответ.

МЕТРИКА — word_similarity из pg_trgm. Замер в БД (факт, не по памяти):

    опечатки:  подрядчико/подрядчиков  0.909
               назначени/назначение    0.900
               заявк/заявку             0.833
               заяву/заявку             0.667   <- наш случай
    чужие:     акт/такт                0.500
               договор/приговор         0.500
               срок/строк               0.400
               па/пп                    0.333
               срок/спрос               0.200
               визу/заяву               0.000

Коридоры НЕ пересекаются: минимум опечаток 0.667, максимум чужих 0.500.
Порог 0.60 разделяет их с запасом в обе стороны.

ПОЧЕМУ НЕ ЛЕВЕНШТЕЙН. Пробовал: расстояние редактирования путает
«срок/строк» (расстояние 1, но разные слова) с «заяву/заявку»
(тоже 1). Пришлось бы вводить правила про приставки, и они ломаются
на других парах. word_similarity различает их по триграммам корректно
и уже посчитана в БД.

ПОЧЕМУ НЕ similarity. Обычная similarity('заяву','заявку') = 0.444 —
слишком низко: она нормирует на объединение триграмм, и короткие слова
страдают. word_similarity сравнивает слово с подстрокой и даёт 0.667.

Стоимость: запрос к БД на пару токенов. Вызывается ТОЛЬКО когда точного
совпадения нет, поэтому на обычных запросах не тратится.
"""

from __future__ import annotations

# Порог word_similarity. Коридор: опечатки >= 0.667, чужие <= 0.500.
# Берём 0.60 — середина с запасом 0.067 снизу и 0.10 сверху.
FUZZY_THRESHOLD = 0.60

# Минимальная длина токена для нечёткого сравнения. Короче — только
# точное совпадение: «па»/«пп» при 0.333 всё равно не пройдут порог,
# но лишний запрос к БД на коротких словах бессмысленен.
MIN_LEN_FOR_FUZZY = 4


def fuzzy_lemmas(
    conn, token_lemmas: list[str], doc_lemmas: set[str]
) -> set[str]:
    """Леммы запроса, для которых в документе есть близкое слово.

    Возвращает подмножество token_lemmas, которые не совпали точно, но
    имеют в doc_lemmas слово с word_similarity >= FUZZY_THRESHOLD.

    Вызывается ТОЛЬКО для токенов без точного совпадения, поэтому
    на обычных запросах запросов к БД не добавляет.
    """
    missing = [
        t for t in token_lemmas
        if t not in doc_lemmas and len(t) >= MIN_LEN_FOR_FUZZY
    ]
    if not missing or not doc_lemmas:
        return set()

    cur = conn.cursor()
    # Один запрос на все пропущенные токены: перебираем их в SQL, а не
    # в цикле из Python — иначе на 8 токенах было бы 8 round-trip.
    cur.execute("""
        SELECT t.lem
        FROM unnest(%s::text[]) AS t(lem)
        WHERE EXISTS (
            SELECT 1 FROM unnest(%s::text[]) AS d(lem2)
            WHERE word_similarity(t.lem, d.lem2) >= %s
        )
    """, (missing, sorted(doc_lemmas), FUZZY_THRESHOLD))
    matched = {r[0] for r in cur.fetchall()}
    cur.close()
    return matched
