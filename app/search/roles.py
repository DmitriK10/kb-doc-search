"""Совпадение роли в вопросе и в пункте регламента.

ЗАЧЕМ. Найдено сверкой номеров пунктов: на вопрос «какой срок назначения
руководителя проекта» система отдавала п. 10.3 — «Срок назначения
АРХИТЕКТОРА проекта – 1 рабочий день», а правильный ответ лежит в п. 9.1:
«Срок назначения РУКОВОДИТЕЛЯ проекта – 1 рабочий день».

ПРИЧИНА. Чанк 9.1 весит 1129 символов: в нём 9.1 + 9.2 + 9.3 + 9.4 + 9.5.
Предложение-ответ тонет среди соседних пунктов. Чанк 10.2.3 короткий
(375 символов) и весь про сроки, поэтому косинусно ближе. Косинус видит
«срок назначения проекта», но не видит, ЧЬЁ назначение.

РЕШЕНИЕ. Роль — это то, что различает пункты, когда тема одна. Если роль
названа и в вопросе, и в пункте — пункт получает бонус; если названа
другая роль — штраф; если роль в пункте не названа — нейтрально
(не штрафуем за отсутствие: пункт может отвечать по существу).

Детерминированно, без модели. Стоимость: ~0.03 мс на чанк.
"""

from __future__ import annotations

import re

# Канонические роли и их написания в регламентах: полное и аббревиатура.
# Взяты из текстов, не выдуманы.
_ROLE_PATTERNS: dict[str, tuple[str, ...]] = {
    "руководитель проекта": (r"руководител\w*\s+проекта", r"\bрп\b"),
    "архитектор": (r"архитектор\w*",),
    "администратор проекта": (r"администратор\w*\s+проекта", r"\bап\b"),
    "главный инженер проекта": (r"главн\w+\s+инженер\w*", r"\bгип\b"),
    "пресейл-архитектор": (r"пресейл-?\s?архитектор\w*", r"\bпа\b"),
    "аккаунт-менеджер": (r"аккаунт-?\s?менеджер\w*", r"\bам\b"),
    "менеджер по продаже решений": (r"менеджер\w*\s+по\s+продаже", r"\bss\b"),
    "ресурс-менеджер": (r"ресурс-?\s?менеджер\w*", r"\bрм\b"),
    "технический пресейл-специалист": (r"пресейл-?\s?специалист\w*", r"\btps\b"),
    "сметчик": (r"сметчик\w*",),
    "координатор департамента": (r"координатор\w*",),
    "заказчик": (r"заказчик\w*",),
    "подрядчик": (r"подрядчик\w*",),
}

# Роли, которые не различают ответ: они есть почти в любом пункте.
# Их совпадение ничего не доказывает, поэтому в сравнении не участвуют.
_NEUTRAL = frozenset({"заказчик", "подрядчик"})


def roles_in(text: str) -> set[str]:
    """Канонические роли, упомянутые в тексте."""
    low = " ".join((text or "").lower().split())
    out: set[str] = set()
    for canon, pats in _ROLE_PATTERNS.items():
        for pat in pats:
            if re.search(pat, low):
                out.add(canon)
                break
    return out


def role_match(query: str, candidates: dict[int, str]) -> dict[int, float]:
    """Совпадает ли роль в чанке с ролью в вопросе.

    candidates: {chunk_id: body}

    Возвращает:
      1.0 — в чанке та же роль, что в вопросе (бонус);
      0.0 — в чанке другая роль, и она не совпадает (штраф);
      0.5 — роль в чанке не названа либо роль в вопросе не найдена
            (нейтрально: не штрафуем за отсутствие).
    """
    q_roles = roles_in(query) - _NEUTRAL
    if not q_roles:
        return {cid: 0.5 for cid in candidates}

    out: dict[int, float] = {}
    for cid, body in candidates.items():
        c_roles = roles_in(body) - _NEUTRAL
        if not c_roles:
            out[cid] = 0.5
        elif c_roles & q_roles:
            out[cid] = 1.0
        else:
            out[cid] = 0.0
    return out