"""Действующие лица в тексте регламента.

ЗАЧЕМ. Пороги косинуса не различают два принципиально разных случая:

  A) «кто назначает РП» — ТЗТ п. 4.1 называет Руководителя отдела
     управления проектами, Проектная ДИБ п. 2.1 — Координатора
     департамента. РАЗНЫЕ ЛЮДИ, ответ зависит от этапа.
  B) «кто согласует ТКП» — оба документа называют ПА. ОДИН И ТОТ ЖЕ
     человек, документы дополняют друг друга.

В обоих случаях два релевантных документа и близкие косинусы. Развилка
нужна только в A: там уверенный ответ из одного документа скрывает
второй и подаёт неполный ответ как полный.

Различитель — набор ролей, УПОМЯНУТЫХ в пункте. Если у каждого документа
есть роль, которой нет у другого, — это A. Если наборы совпадают или один
вложен в другой, — это B.

Детерминированно, без модели и без сети. Стоимость: ~0.02 мс на чанк.

ПОЧЕМУ НЕ ГЛАГОЛЫ. Первая версия искала исполнителя после глаголов
(«назначает», «отвечает за»). Проверка показала, что в регламентах
исполнитель стоит и до глагола: «За назначение РП на этапе пресейла
отвечает Руководитель отдела...». Разбор по ролям надёжнее и проще.
"""

from __future__ import annotations

import re

# Известные роли и их канонические имена.
#
# Порядок важен: длинные проверяются раньше, иначе «руководитель отдела»
# поймается как «руководитель проекта».
#
# Взяты из реальных регламентов: встретились в текстах, не выдуманы.
_ROLES: list[tuple[str, str]] = [
    ("ресурсного менеджера", "ресурс-менеджер"),
    ("ресурс-менеджер", "ресурс-менеджер"),
    ("ресурсный менеджер", "ресурс-менеджер"),
    ("руководитель группы управления проектами",
     "руководитель группы УП"),
    ("руководителя группы управления проектами",
     "руководитель группы УП"),
    ("руководитель отдела управления проектами",
     "руководитель отдела УП"),
    ("руководителя отдела управления проектами",
     "руководитель отдела УП"),
    ("руководитель департамента", "руководитель департамента"),
    ("руководителя департамента", "руководитель департамента"),
    ("координатор департамента", "координатор департамента"),
    ("координатора департамента", "координатор департамента"),
    ("пресейл-архитектор", "пресейл-архитектор"),
    ("пресейл-архитектора", "пресейл-архитектор"),
    ("архитектор пресейла", "пресейл-архитектор"),
    ("администратор проекта", "администратор проекта"),
    ("администратора проекта", "администратор проекта"),
    ("главный инженер проекта", "главный инженер проекта"),
    ("главного инженера проекта", "главный инженер проекта"),
    ("менеджер по продаже решений", "менеджер по продаже решений"),
    ("менеджера по продаже решений", "менеджер по продаже решений"),
    ("аккаунт-менеджер", "аккаунт-менеджер"),
    ("аккаунт-менеджера", "аккаунт-менеджер"),
    ("технический пресейл-специалист", "технический пресейл-специалист"),
    ("сметчик", "сметчик"),
    ("сметчика", "сметчик"),
]

# Участники, а не исполнители: «заказчик», «подрядчик», «служба качества».
# Их различие НЕ делает ответ неоднозначным — они объект действия,
# а не тот, кто его выполняет. Исключены из сравнения сознательно:
# на «кто согласует ТКП» они давали ложную развилку.

# Аббревиатуры ролей: в регламентах пишут и так. Каждая — отдельная роль,
# потому что именно они различают документы («назначает РП» vs «назначает ПА»).
_ABBR: dict[str, str] = {
    "рп": "РП",
    "ss": "SS",
    "ам": "АМ",
    "па": "ПА",
    "tps": "TPS",
    "tss": "TSS",
    "гип": "ГИП",
    "ап": "АП",
    "рм": "РМ",
}


def extract_actors(body: str) -> set[str]:
    """Роли, упомянутые в тексте пункта.

    «4.1. За назначение РП на этапе пресейла отвечает Руководитель отдела
    управления проектами» -> {'РП', 'руководитель отдела УП'}
    """
    text = " ".join((body or "").split())
    low = text.lower()
    out: set[str] = set()

    for key, canon in _ROLES:
        if key in low:
            out.add(canon)

    # Аббревиатуры — по границе слова, чтобы «рп» не поймалось внутри слова.
    for abbr, canon in _ABBR.items():
        if re.search(rf"(?<![а-яёa-z]){re.escape(abbr)}(?![а-яёa-z])", low):
            out.add(canon)

    return out


def actors_differ(candidates: list[dict]) -> tuple[bool, dict[str, list[str]]]:
    """Называют ли документы РАЗНЫХ исполнителей.

    candidates: [{"doc_title", "body"}] — по одному лучшему чанку с каждого
    документа.

    Возвращает (различаются_ли, роли_по_документам).

    True означает, что развилка уместна: показав только один документ,
    система подаст неполный ответ как полный. Это и есть требование
    п. 7.5б брифинга.

    Логика: развилка нужна, если у каждого документа есть роль,
    отсутствующая у другого. Если наборы совпадают или один целиком
    вложен в другой — документы дополняют друг друга, ответ однозначен.
    """
    per_doc: dict[str, set[str]] = {}
    for c in candidates:
        acts = extract_actors(c.get("body") or "")
        if acts:
            per_doc.setdefault(c["doc_title"], set()).update(acts)

    if len(per_doc) < 2:
        return False, {k: sorted(v) for k, v in per_doc.items()}

    docs = list(per_doc.items())[:3]
    base_acts = docs[0][1]
    for _, acts in docs[1:]:
        # Уникальные роли с каждой стороны.
        base_only = base_acts - acts
        other_only = acts - base_acts
        if base_only and other_only:
            return True, {k: sorted(v) for k, v in per_doc.items()}

    return False, {k: sorted(v) for k, v in per_doc.items()}