"""Сборка запроса к полнотекстовому поиску: токенизация, стоп-фильтр, потолок групп.

Правки раунда 4, принятые в код:
  К1. Класс токена расширен до `[.-]` внутри слова: «2.3» больше не режется
      на «2» и «3». Числовые и короткие токены отбрасываются из AND-цепочки.
      ВАЖНО: версия документа («2.3», «v2.3») не выбрасывается, а уходит
      отдельным списком `versions` — её фильтруют структурно по
      documents.version, а не полнотекстом. Иначе запрос «регламент 2.3»
      теряет единственный различающий токен.
  К2. Потолок групп — 8. AND по 40 группам не находит ничего: развёрнутый
      вопрос даёт 10+ групп, FTS-ветка молча умирает, RRF вырождается
      в векторный. Лишние токены дропаются: их смысл покрывает вектор.

Расширение синонимами живёт в SQL (kb_expand_query), а не здесь: сравнение
идёт в лексемном пространстве, поэтому и нормализация должна делаться
словарём PostgreSQL, а не поверхностными формами в Python.

Стоимость: ~0.05 мс на запрос. RAM: 0.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# К2: потолок AND-групп.
MAX_GROUPS = 8

# Класс токена: буквы/цифры, внутренняя точка или дефис (К1).
_TOKEN_RE = re.compile(r"[0-9a-zA-Zа-яё]+(?:[.-][0-9a-zA-Zа-яё]+)*", re.IGNORECASE)

# Токен, пригодный как AND-группа: только буквы и дефис, минимум 2 символа.
_ALPHA_RE = re.compile(r"[a-zа-яё][a-zа-яё-]{1,}", re.IGNORECASE)

# Номер версии или пункта: «2.3», «v2.3», «1.0». Уходит в structural-фильтр.
_VERSION_RE = re.compile(r"^[vVтТ]?\d+(?:\.\d+)+$")

# Стоп-слова. Русский словарь PostgreSQL отбрасывает их и сам, но здесь они
# нужны, чтобы не занимать слот из MAX_GROUPS.
STOPWORDS = frozenset({
    "а", "без", "более", "бы", "был", "была", "были", "было", "быть", "в",
    "вам", "вас", "весь", "во", "вот", "все", "всего", "всех", "вы", "где",
    "да", "даже", "для", "до", "его", "ее", "ей", "если", "есть", "еще",
    "же", "за", "здесь", "и", "из", "или", "им", "их", "к", "как", "какая",
    "какие", "каким", "каких", "какой", "когда", "кого", "кому", "которая",
    "которые", "который", "которых", "кто", "ли", "либо", "мне", "может",
    "можно", "мы", "на", "над", "надо", "нам", "нас", "наш", "не", "него",
    "нее", "нет", "ни", "но", "ну", "нужно", "о", "об", "однако", "он", "она",
    "они", "оно", "от", "очень", "по", "под", "при", "про", "с", "сам", "сво",
    "себе", "так", "также", "такой", "там", "те", "тем", "то", "того", "тоже",
    "той", "только", "том", "ты", "у", "уже", "хотя", "чего", "чей", "чем",
    "через", "что", "чтобы", "чья", "эта", "эти", "это", "этот", "я",
})


@dataclass(slots=True)
class PreparedQuery:
    """Готовый к отправке в SQL запрос.

    tokens:   список токенов для kb_tsquery(tokens) — AND по группам,
              OR по синонимам внутри группы (расширение делает SQL).
    versions: номера версий из запроса — повод для фильтра по documents.version.
    """

    tokens: list[str] = field(default_factory=list)
    versions: list[str] = field(default_factory=list)
    dropped: dict[str, int] = field(default_factory=dict)

    @property
    def is_empty(self) -> bool:
        """Нет содержательных токенов — FTS-ветку не запускаем (иначе NULL)."""
        return not self.tokens

    @property
    def n_groups(self) -> int:
        return len(self.tokens)


def fold_yo(tok: str) -> str:
    """Складывает ё -> е ТОЛЬКО для сравнения со стоп-листом.

    Зачем отдельная функция: сам токен в tsquery должен уйти в исходной
    форме (иначе асимметрия с to_tsvector, см. комментарий в tokenize),
    но стоп-лист в коде написан через «е», и без складывания «ещё» перестаёт
    считаться служебным словом и занимает слот из MAX_GROUPS.
    """
    return tok.replace("ё", "е")


def tokenize(text: str) -> list[str]:
    """Токенизация: нижний регистр, сохранение точек/дефисов внутри токена.

    ВАЖНО про ё/е. Замена ё -> е здесь УБРАНА сознательно.

    Раньше токенизатор делал .replace("ё", "е") только над запросом, а
    to_tsvector('russian') над документом — не делал. Это создавало асимметрию:
    документ давал лексему «отчёт», запрос — «отчет», и FTS не сходился.
    Теперь обе стороны нормализуются одним словарём PostgreSQL (russian_stem),
    и ручная замена только вредит: она может дать лексему, которой в индексе
    нет. Унификация ё/е, если она нужна, должна быть одинаковой на обеих
    сторонах — то есть в to_tsvector и kb_lemma, а не в клиенте.

    Стоп-лист ниже содержит слова через «е», поэтому сравнение идёт по
    «е»-форме: для служебных слов («еще», «ее») это безопасно, а ё в них
    не встречается в деловых текстах иначе как в «ещё» — слово и так
    отбрасывается словарём PostgreSQL.
    """
    if not text:
        return []
    out: list[str] = []
    for m in _TOKEN_RE.finditer(text.lower()):
        tok = m.group(0).strip(".-")
        if tok:
            out.append(tok)
    return out


def prepare(text: str, max_groups: int = MAX_GROUPS) -> PreparedQuery:
    """Готовит запрос: стоп-фильтр, отбрасывание чисел (К1), потолок групп (К2).

    Числовые токены («500», «45») сознательно не входят в AND-цепочку:
    «до 500 тысяч» против «до 500 000 рублей» лексемно не совпадёт никогда,
    а односимвольные группы матчатся почти везде. Смысловые числа проверяет
    числовой guard в grounding.py — детерминированно и без полнотекста.

    Версии («2.3», «v2.3») — исключение: они различают документы, поэтому
    сохраняются в PreparedQuery.versions для структурного фильтра.
    """
    pq = PreparedQuery(dropped={})
    seen: set[str] = set()

    def bump(key: str) -> None:
        pq.dropped[key] = pq.dropped.get(key, 0) + 1

    for tok in tokenize(text):
        # Стоп-фильтр сравнивает по «е»-форме: сам токен остаётся как есть
        # (симметрия с to_tsvector), но «ещё» распознаётся как служебное слово.
        if fold_yo(tok) in STOPWORDS:
            bump("stopword")
            continue

        # Версия/номер пункта: помним отдельно и в AND не берём —
        # её место в структурном фильтре, а не в полнотексте.
        if _VERSION_RE.match(tok):
            if tok not in pq.versions:
                pq.versions.append(tok)
            bump("version")
            continue

        if tok in seen:
            bump("duplicate")
            continue

        # К1: числа и слишком короткие токены — только в вектор, не в AND.
        if not _ALPHA_RE.fullmatch(tok):
            bump("numeric" if any(c.isdigit() for c in tok) else "short")
            continue

        # К2: потолок групп.
        if len(pq.tokens) >= max_groups:
            bump("overflow")
            continue

        seen.add(tok)
        pq.tokens.append(tok)

    return pq


def strip_version_prefix(version: str) -> str:
    """'v2.3' -> '2.3', 'т2.3' -> '2.3'. Для сравнения с documents.version."""
    return version.lstrip("vVтТ")