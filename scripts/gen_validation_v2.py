BAD_STARTS = ("с ", "со ", "на ", "в ", "во ", "по ", "из ", "от ", "до ",
              "к ", "ко ", "за ", "при ", "о ", "об ", "для ", "без ", "через ")


def _valid_phrase(phrase: str) -> bool:
    """Годна ли извлечённая фраза для подстановки в вопрос.

    Дефект: extract_action выдёргивал продолжение, начинающееся с предлога,
    и получались вопросы вида «сколько времени даётся на с юридическим
    департаментом». Система на них честно отказывалась, но в метрике это
    выглядело как ложный отказ — хотя это дефект набора, а не поиска.
    """
    p = phrase.strip().lower()
    if len(p) < 4:
        return False
    for bad in BAD_STARTS:
        if p.startswith(bad):
            return False
    return any(len(w) > 3 for w in p.split())


def classify(text: str) -> str:
    """Тип пункта по ключевым словам — для выбора шаблона вопроса."""
    low = text.lower()
    if any(w in low for w in ("не позднее", "в течение", "срок", "дней")):
        return "срок"
    if any(w in low for w in ("подписыва", "подписант", "визир")):
        return "подписание"
    if any(w in low for w in ("ответствен", "отвечает", "возложен")):
        return "ответственный"
    if any(w in low for w in ("рублей", "процент", "размере", "лимит")):
        return "сумма"
    if any(w in low for w in ("запрещ", "не допускается", "нельзя")):
        return "запрет"
    return "порядок"


def extract_object(text: str) -> str:
    """Короткая фраза-объект для подстановки в шаблон."""
    low = text.lower()
    for marker in ("подписывает ", "в размере ", "на сумму ", "лимит ",
                   "размер ", "сумма "):
        i = low.find(marker)
        if i >= 0:
            frag = text[i + len(marker):].strip().split(".")[0].split(",")[0]
            if 3 < len(frag) < 55:
                return frag.lower()
    return "это"


def extract_action(text: str) -> str:
    """Действие для шаблонов «как …», «в какой срок …»."""
    low = text.lower()
    for marker in ("оформляется ", "проводится ", "подаётся ", "сдаётся ",
                   "выплачиваются ", "согласуется ", "предоставляется ",
                   "проводится ", "пересматриваются ", "закрывается ",
                   "фиксируется ", "блокируется ", "обновляется ",
                   "вносится ", "направляется ", "составляется ",
                   "подписывается ", "утверждается ", "применяется "):
        i = low.find(marker)
        if i >= 0:
            frag = text[i + len(marker):].strip().split(".")[0]
            if 3 < len(frag) < 60:
                return frag.lower()
    return "оформить это"


def main() -> int:
    ap = argparse.ArgumentParser(description="Расширенный валидационный набор")
    ap.add_argument("--corpus", default="data/corpus")
    ap.add_argument("--out-dir", default="data")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    rnd = random.Random(args.seed)
    corpus = Path(args.corpus)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    manifest = json.loads((corpus / "manifest.json").read_text(encoding="utf-8"))
    meta_by_file = {d["file"]: d for d in manifest["documents"]}

    # --- 1. Пункты активных документов ---
    pool: list[dict] = []
    for path in sorted(corpus.glob("*.docx")):
        info = meta_by_file.get(path.name, {})
        if info.get("valid_to"):
            continue        # из недействительных версий обычные вопросы не строим
        doc = parse_docx(path)
        for ch in chunk_document(doc):
            if ch.chunk_type != "item" or ch.char_len < 50:
                continue
            pool.append({
                "doc_title": doc.title,
                "file": path.name,
                "section_path": ch.section_path,
                "body": ch.body,
            })

    print(f"пунктов-кандидатов: {len(pool)}")

    records: list[dict] = []
    seen: set[str] = set()

    def add(query: str, gold: dict | None, *, oos=False, stale=False, reg="template"):
        q = query.strip().lower()
        if q in seen or len(query.strip()) < 8:
            return False
        seen.add(q)
        records.append({
            "query": query.strip(),
            "gold": gold,
            "out_of_scope": oos,
            "is_stale": stale,
            "register": reg,
        })
        return True

    # --- 2. Бытовые вопросы (самые ценные) ---
    for q, doc, sec in COLLOQUIAL:
        add(q, {"doc_title": doc, "section_path": sec}, reg="colloquial")

    # --- 3. Шаблонные вопросы по пунктам ---
    #
    # Два вопроса на пункт разными шаблонами: один шаблон даёт 79 вопросов,
    # а нужно 150. При этом КАЧЕСТВО фильтруется: если объект или действие
    # не извлеклись, вопрос отбрасывается.
    #
    # Почему это важно: шаблон с заглушкой «это» даёт «кто должен подписать
    # это» — такой вопрос не проверяет поиск по смыслу, он проверяет
    # случайность извлечения. Раньше такие попадали в набор.
    BAD_STUBS = ("это", "этот вопрос", "оформить это")

    def build_questions(item: dict) -> list[str]:
        kind = classify(item["body"])
        obj = extract_object(item["body"])
        act = extract_action(item["body"])
        out = []
        # Перемешиваем шаблоны детерминированно (seed), берём до двух.
        tmpls = list(TEMPLATES[kind])
        rnd.shuffle(tmpls)
        # Проверяем фразы ДО подстановки: мусорная фраза даёт мусорный вопрос.
        obj_ok = _valid_phrase(obj)
        act_ok = _valid_phrase(act)
        for tmpl in tmpls[:2]:
            if "{obj}" in tmpl and not obj_ok:
                continue
            if "{act}" in tmpl and not act_ok:
                continue
            try:
                q = tmpl.format(obj=obj, act=act)
            except KeyError:
                continue
            low = q.lower()
            # Отбрасываем заглушки: вопрос должен называть предмет.
            if any(stub in low for stub in BAD_STUBS):
                continue
            # Отбрасываем слишком короткие и слишком длинные.
            if not (15 <= len(q) <= 95):
                continue
            out.append(q)
        return out

    for item in pool:
        for q in build_questions(item):
            add(q, {"doc_title": item["doc_title"],
                    "section_path": item["section_path"]})

    # --- 4. Out-of-scope ---
    for q in OUT_OF_SCOPE:
        add(q, None, oos=True, reg="out_of_scope")

    # --- 5. Stale (про недействительную версию) ---
    for q in STALE_QUESTIONS:
        add(q, None, stale=True, reg="stale")

    # --- 5b. Вопросы про действующую версию — обычные in-scope ---
    # Проверяют, что фильтр актуальности отдаёт 3.1, а не 2.3.
    for q in CURRENT_VERSION_QUESTIONS:
        add(q, {"doc_title": "Регламент согласования и подписания договоров",
                "section_path": "4.1"}, reg="colloquial")

    print(f"собрано записей: {len(records)}")

    # --- 6. Сплит ---
    normal = [r for r in records if not r["out_of_scope"] and not r["is_stale"]]
    oos = [r for r in records if r["out_of_scope"]]
    stale = [r for r in records if r["is_stale"]]

    rnd.shuffle(normal)
    rnd.shuffle(oos)

    # Делим КАЖДЫЙ класс пополам, чтобы test не остался без out-of-scope.
    #
    # Прошлая версия брала oos[:30] в dev и oos[30:60] в test, но
    # out-of-scope всего 41 — в test попало 11. Precision на 11 точках
    # лучше, чем на 8, но всё ещё шумно.
    #
    # Правило: пропорция 55/45 по каждому классу. Тогда in-scope ~90/60,
    # out-of-scope ~22/19, stale ~6/4. Test получает достаточно обоих.
    def split_class(items: list, dev_share: float = 0.55) -> tuple[list, list]:
        n = max(1, int(len(items) * dev_share))
        return items[:n], items[n:]

    norm_dev, norm_test = split_class(normal, 0.60)
    oos_dev, oos_test = split_class(oos, 0.55)
    stale_dev, stale_test = split_class(stale, 0.55)

    dev = norm_dev + oos_dev + stale_dev
    test = norm_test + oos_test + stale_test

    rnd.shuffle(dev)
    rnd.shuffle(test)

    for name, split in (("validation_dev.jsonl", dev),
                        ("validation_test.jsonl", test)):
        path = out_dir / name
        path.write_text(
            "\n".join(json.dumps(r, ensure_ascii=False) for r in split),
            encoding="utf-8",
        )
        n_in = sum(1 for r in split if not r["out_of_scope"] and not r["is_stale"])
        n_out = sum(1 for r in split if r["out_of_scope"])
        n_st = sum(1 for r in split if r["is_stale"])
        print(f"{name:24s} всего={len(split):3d} "
              f"in-scope={n_in:3d} out-of-scope={n_out:2d} stale={n_st}")

    print(f"\nвсего: {len(records)}")
    return 0


