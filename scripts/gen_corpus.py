"""Генератор корпуса DOCX по контракту парсера.

Воспроизводит конвенции эталонного образца reg_dogovora_v3.1.docx:
  1. Заголовок — стиль Title.
  2. Шапка метаданных — отдельный абзац сразу после Title, форма
     «Версия 3.1. Действует с 01.03.2026. Владелец: Юридический департамент
      (legal@company.ru).»
  3. Разделы — Heading 1 с нумерацией «1. Название».
  4. Пункты — отдельные абзацы «1.1. Текст».
  5. Таблицы — шапка в первой строке, подпись «Таблица N. ...» перед ней.

Состав корпуса:
  - 17 действующих документов по разным темам (договоры, командировки,
    закупки, NDA, ИБ, отпуска, архив, CRM, премии, штат, удалёнка, обучение,
    печать, заявки, медосмотр, пожарная безопасность, делопроизводство);
  - 3 версии одного документа (регламент договоров v2.3 и v3.1) — для
    демонстрации фильтра актуальности;
  - 3 темы, которых НЕТ в базе (доверенности, командировки за рубеж,
    ИБ-инциденты) — источник красной зоны на дашборде. Это не «дырка в
    демо», а намеренно воспроизведённый сценарий: таких запросов в реальной
    компании 20–25%, и система обязана на них отказывать.

Запуск: python scripts/gen_corpus.py --out data/corpus
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass, field
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt


@dataclass
class Item:
    """Пункт регламента."""

    num: str
    text: str


@dataclass
class Table:
    """Таблица с подписью и шапкой."""

    caption: str
    header: list[str]
    rows: list[list[str]]


@dataclass
class Section:
    """Раздел с пунктами и (опционально) таблицей."""

    num: str
    title: str
    items: list[Item] = field(default_factory=list)
    table: Table | None = None


@dataclass
class DocSpec:
    """Описание документа для генерации."""

    doc_key: str
    title: str
    version: str
    valid_from: str          # ISO
    owner_unit: str
    owner_email: str
    owner_role: str
    doc_type: str
    sections: list[Section]
    valid_to: str | None = None
    replaces: str | None = None
    access_groups: list[str] = field(default_factory=lambda: ["all"])


def _ru_date(iso: str) -> str:
    """2026-03-01 -> 01.03.2026 (формат шапки эталона)."""
    y, m, d = iso.split("-")
    return f"{d}.{m}.{y}"


def build_docx(spec: DocSpec, out_dir: Path) -> Path:
    """Собирает DOCX по контракту парсера."""
    doc = Document()

    # Стили: у python-docx есть Title и Heading N из шаблона по умолчанию,
    # но русская локаль даёт «Заголовок 1». Парсер понимает оба, однако для
    # предсказуемости фиксируем английские имена — как в эталоне.
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)

    doc.add_paragraph(spec.title, style="Title")

    # Шапка метаданных — ОДИН абзац, форма эталона.
    #
    # Дата окончания действия пишется ОБЯЗАТЕЛЬНО, если версия устарела.
    # Без неё парсер оставляет valid_to = NULL, диапазон версии становится
    # [valid_from, infinity), и EXCLUDE-ограничение documents_no_overlap
    # отвергает вставку следующей версии. Это не ошибка ограничения, а
    # сигнал, что документ не несёт дату окончания — а без неё система
    # не может отличить действующий регламент от отменённого.
    meta = f"Версия {spec.version}. Действует с {_ru_date(spec.valid_from)}."
    if spec.valid_to:
        meta += f" Действует до {_ru_date(spec.valid_to)}."
    meta += f" Владелец: {spec.owner_unit} ({spec.owner_email})."
    doc.add_paragraph(meta)

    for sec in spec.sections:
        doc.add_paragraph(f"{sec.num}. {sec.title}", style="Heading 1")
        for it in sec.items:
            doc.add_paragraph(f"{it.num}. {it.text}")

        if sec.table:
            doc.add_paragraph(sec.table.caption)
            table = doc.add_table(rows=1, cols=len(sec.table.header))
            table.style = "Table Grid"
            hdr = table.rows[0].cells
            for i, h in enumerate(sec.table.header):
                hdr[i].text = h
            for row in sec.table.rows:
                cells = table.add_row().cells
                for i, v in enumerate(row):
                    cells[i].text = v

    out_dir.mkdir(parents=True, exist_ok=True)
    # Имя файла содержит версию, но doc_key из него срезается парсером:
    # reg_dogovora_v2.3.docx и reg_dogovora_v3.1.docx дают один doc_key.
    name = f"{spec.doc_key}_v{spec.version}.docx"
    path = out_dir / name
    doc.save(str(path))
    return path


