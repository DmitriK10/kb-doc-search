-- ============================================================================
-- 007_glossary_synonyms.sql — русские синонимы из глоссария организаторов
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ МИГРАЦИЯ. 006 добавила аббревиатуры корпуса (РП, ТКП, ПА)
-- с УЗКИМИ вариантами: только однозначные эквиваленты, чтобы не засорять
-- FTS общими словами. Это правильно для аббревиатур.
--
-- Но глоссарий организаторов (п. 6.3 брифа) называет ДРУГОЙ класс пар:
-- обиходные слова, которыми сотрудники называют то, что в регламенте
-- написано иначе. «Проджект менеджер» вместо «руководитель проекта»,
-- «БПМ» вместо «бизнес-процессы», «КС-2» вместо «акт о приёмке».
-- Такие пары в 006 отсутствуют: там были только корпусные аббревиатуры.
--
-- ПОЧЕМУ НЕ В 006. 006 — про часто встречающиеся аббревиатуры корпуса,
-- с частотами и узкими вариантами. Здесь — про перефразы сотрудников,
-- частот в корпусе у них нет (этих слов в регламентах не пишут).
-- Смешивать два разных обоснования в одной миграции значило бы потерять
-- и то, и другое.
--
-- ГРАНИЦА: глоссарий организаторов в КОРПУС не кладём (заказчик: «для
-- вашего понимания»). Здесь он живёт только как словарь расширения запроса
-- и не цитируется как источник.
--
-- RAM: +15 строк. Стоимость: те же 0.1–0.3 мс на запрос.
-- ============================================================================

INSERT INTO term_synonyms (term, expand) VALUES
    -- Роли в обиходных словах. Варианты однозначные: «проджект» не может
    -- означать ничего другого, поэтому добавляем и его самого, и канон.
    ('проджект', ARRAY['проджект', 'руководител']),
    ('проект менеджер', ARRAY['проект', 'менеджер', 'руководител']),
    ('аккаунт', ARRAY['аккаунт', 'клиент']),
    ('пресейл', ARRAY['пресейл', 'presale', 'предпродажа']),

    -- Документы и артефакты в обиходных названиях.
    -- КС-2 в обиходе называют «акт выполненных работ»: в самом регламенте
    -- стоит «формы КС-2 и КС-3», расшифровки нет.
    ('акт', ARRAY['акт', 'кс-2', 'кс2']),
    ('смета', ARRAY['смета', 'сметчик', 'кс-3', 'кс3']),
    ('счёт', ARRAY['счёт', 'счет', 'упд', 'фактура']),

    -- Предметные термины из глоссария организаторов.
    -- БПМ = бизнес-процессы: аббревиатура встречается в вопросах
    -- сотрудников, в регламентах пишут полностью.
    ('бпм', ARRAY['бпм', 'бизнес', 'процесс']),
    ('тз', ARRAY['тз', 'задание', 'техническое']),
    ('ртз', ARRAY['ртз', 'трудозатрат', 'трудозатраты', 'расчёт', 'расчет']),
    ('знп', ARRAY['знп', 'заявка', 'заявки', 'заявку', 'пресейл']),

    -- Сроки и согласование — частые слова вопросов.
    ('дедлайн', ARRAY['дедлайн', 'срок', 'дней']),
    ('эскалация', ARRAY['эскалация', 'эскалируется', 'руководителя']),
    ('дисквалификация', ARRAY['дисквалификация', 'дисквалифицировать',
                              'отказ', 'производства']),
    ('хардоффер', ARRAY['хардоффер', 'хард', 'оффер']),
    ('подрядчик', ARRAY['подрядчик', 'субподрядчик', 'партнер', 'партнёр'])
ON CONFLICT (term) DO UPDATE SET expand = EXCLUDED.expand;

-- ----------------------------------------------------------------------------
-- Проверка: варианты однословные, tsquery собирается, ключевые пары работают.
-- ----------------------------------------------------------------------------
DO $$
DECLARE
    n INT;
    bad INT;
    q tsquery;
BEGIN
    SELECT count(*) INTO n FROM term_synonyms;
    RAISE NOTICE 'терминов в словаре: %', n;

    SELECT count(*) INTO bad
    FROM term_synonyms s, unnest(s.expand) AS v
    WHERE v LIKE '% %';
    IF bad > 0 THEN
        RAISE EXCEPTION 'вариантов с пробелом: % — to_tsquery упадёт', bad;
    END IF;

    -- «БПМ» должно разворачиваться в «бизнес» и «процесс».
    q := kb_tsquery(ARRAY['бпм']);
    RAISE NOTICE 'БПМ -> %', q;

    -- «проджект менеджер» -> руководитель.
    q := kb_tsquery(ARRAY['проджект']);
    RAISE NOTICE 'проджект -> %', q;
END $$;

COMMENT ON TABLE term_synonyms IS
    'Словарь расширения запроса. 006 — аббревиатуры корпуса (узкие варианты). '
    '007 — обиходные пары из глоссария организаторов (проджект менеджер -> РП, '
    'БПМ -> бизнес-процессы, КС-2 -> акт). Только ОДНОСЛОВНЫЕ варианты: '
    'to_tsquery не принимает строки с пробелом. Глоссарий НЕ является '
    'документом корпуса: он не цитируется как источник, только расширяет запрос.';