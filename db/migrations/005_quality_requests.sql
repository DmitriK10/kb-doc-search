-- ============================================================================
-- 005_quality_requests.sql — кейс 1 и 3: запросы в службу качества
--
-- БРИФ (цитата): «При отсутствии информации в регламенте не должен давать
-- недостоверный ответ, а должен создать запрос в службу качества компании
-- (либо давать пользователю соответствующий ответ "обратитесь туда-то",
-- либо отправлять письмо на адрес службы качества)».
--
-- Требуется ТРИ вещи, и они разные:
--   1. КЕЙС 1 — запрос в службу качества с номером. Пользователь получает
--      «обратитесь в службу качества, запрос №K-123 создан».
--   2. КЕЙС 3 — дообучение: сотрудник службы качества даёт ответ, агент
--      пополняет базу знаний и привязывает ответ к регламенту.
--   3. Модерация: ответ владельца попадает в базу только после проверки
--      (бриф: «пополняет свою базу знаний нужной информацией» — но
--      непроверенный ответ противоречил бы гарантии достоверности).
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, а не knowledge_alerts: knowledge_alerts — это
-- сигналы владельцам о белых пятнах (кластеры). Здесь другой объект:
-- конкретный вопрос сотрудника с ответом службы качества и статусом
-- модерации. Смешивать нельзя: у них разный жизненный цикл.
--
-- RAM: 0. Стоимость: один INSERT на отказ (~1 мс).
-- ============================================================================

CREATE TABLE IF NOT EXISTS quality_requests (
    id            BIGSERIAL PRIMARY KEY,
    -- Серийный номер для пользователя: K-123. Генерируется из id при показе,
    -- но хранится и здесь, чтобы номер не менялся при смене формата.
    public_id     TEXT NOT NULL UNIQUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Вопрос и контекст. ВАЖНО про 152-ФЗ: здесь сырой текст ХРАНИТСЯ,
    -- потому что без него сотрудник службы качества не ответит. Это
    -- осознанное исключение из правила «HMAC без текста»: пользователь
    -- сам отправляет вопрос в службу качества, то есть даёт согласие
    -- на обработку. В query_logs по-прежнему HMAC.
    question      TEXT NOT NULL,
    user_id_hash  CHAR(64) NOT NULL,

    -- Что нашла система до отказа: топ-чанки, чтобы сотрудник видел,
    -- что уже проверено и не искал заново.
    closest_chunks JSONB NOT NULL DEFAULT '[]'::jsonb,
    confidence    REAL,
    coverage      REAL,

    -- Статус обработки службой качества.
    status        TEXT NOT NULL DEFAULT 'open'
                  CHECK (status IN ('open', 'answered', 'closed')),

    -- Ответ сотрудника службы качества (кейс 3).
    answer        TEXT,
    answered_by   TEXT,
    answered_at   TIMESTAMPTZ,

    -- К какому регламенту привязан ответ. Бриф: «привязывает его
    -- к регламенту». NULL, если сотрудник не указал документ.
    doc_key       TEXT,
    section_path  TEXT,

    -- Модерация: ответ попадает в поиск только после проверки.
    -- Иначе непроверенный ответ нарушил бы гарантию достоверности.
    moderation    TEXT NOT NULL DEFAULT 'pending'
                  CHECK (moderation IN ('pending', 'approved', 'rejected')),
    moderated_by  TEXT,
    moderated_at  TIMESTAMPTZ,

    -- Ссылка на чанк, созданный из ответа (после одобрения).
    chunk_id      BIGINT REFERENCES chunks(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS quality_requests_status
    ON quality_requests (status, created_at DESC);
CREATE INDEX IF NOT EXISTS quality_requests_moderation
    ON quality_requests (moderation) WHERE moderation = 'pending';

COMMENT ON TABLE quality_requests IS
    'Кейс 1 и 3: запрос в службу качества и контур дообучения. '
    'Сырой текст вопроса хранится осознанно: без него сотрудник не ответит, '
    'а пользователь сам отправляет вопрос (согласие на обработку).';
COMMENT ON COLUMN quality_requests.public_id IS
    'Номер для пользователя: K-123. Показывается в ответе агента.';
COMMENT ON COLUMN quality_requests.moderation IS
    'Ответ службы качества попадает в поиск только после approved. '
    'Иначе непроверенный ответ нарушил бы гарантию достоверности.';

-- ----------------------------------------------------------------------------
-- Дополнения службы качества как источник в поиске.
--
-- Бриф: «агент пополняет базу знаний нужной информацией и привязывает его
-- к регламенту». Значит ответ должен быть находим наравне с пунктами
-- регламента, но с явной пометкой происхождения.
--
-- Почему отдельная таблица, а не сразу chunk: ответ службы качества —
-- это не пункт регламента. Показывать его как «пункт 4.2 регламента»
-- было бы подменой источника. Он идёт как отдельный источник с меткой
-- «дополнено службой качества».
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS quality_knowledge (
    id            BIGSERIAL PRIMARY KEY,
    request_id    BIGINT NOT NULL REFERENCES quality_requests(id) ON DELETE CASCADE,
    -- Текст ответа — то, что будет цитироваться пользователю.
    body          TEXT NOT NULL,
    -- Привязка к регламенту (бриф: «привязывает к регламенту»).
    doc_key       TEXT,
    section_path  TEXT,
    doc_title     TEXT,
    -- Эмбеддинг ответа: ищем его тем же векторным поиском.
    embedding     halfvec(312) NOT NULL,
    -- tsv для полнотекста: та же функция, что у чанков.
    tsv           tsvector GENERATED ALWAYS AS (kb_tsv(body, 'A')) STORED,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS quality_knowledge_tsv
    ON quality_knowledge USING gin (tsv);
CREATE INDEX IF NOT EXISTS quality_knowledge_active
    ON quality_knowledge (is_active) WHERE is_active;

COMMENT ON TABLE quality_knowledge IS
    'Ответы службы качества после модерации. Отдельный источник: '
    'показывается с меткой «дополнено службой качества», а не как '
    'пункт регламента — иначе источник был бы подменён.';

-- ----------------------------------------------------------------------------
-- Номер запроса K-{id}. Функция, а не триггер: номер нужен при вставке,
-- чтобы вернуть его пользователю в том же ответе.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION kb_next_quality_id()
RETURNS TEXT
LANGUAGE sql
VOLATILE
AS $$
    SELECT 'K-' || nextval('quality_requests_id_seq');
$$;

COMMENT ON FUNCTION kb_next_quality_id() IS
    'Серийный номер запроса в службу качества: K-123. Использует тот же '
    'sequence, что и id, поэтому номера не пересекаются.';