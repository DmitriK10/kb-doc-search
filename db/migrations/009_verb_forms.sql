-- ============================================================================
-- 009_verb_forms.sql — глагольные формы в словаре расширения
--
-- ДЕФЕКТ, найденный живым тестом. Вопрос «когда подавать заявку на обучение»
-- не находил п. 2.1 Регламента корпоративного обучения («Заявка на обучение
-- ПОДАЁТСЯ руководителем подразделения не позднее чем за 15 рабочих дней»),
-- а отдавал чужие пункты Пресейловой деятельности.
--
-- ПРИЧИНА — лемматизатор PostgreSQL. Он не сводит возвратную и инфинитивную
-- формы одного глагола:
--
--     kb_lemma('подавать') = 'подава'
--     kb_lemma('подаётся') = 'пода'      <- разные леммы!
--
-- Замер по корпусу: 8 чанков содержат «подаётся»/«подаёт», и ни один
-- не находился по запросу с «подавать». Это не край, а системный разрыв:
-- сотрудник спрашивает инфинитивом («когда подавать»), регламент пишет
-- возвратной формой («заявка подаётся»).
--
-- Проверено, что расхождение системное, а не только у «подавать»:
--     согласовывать/согласуется  -> 'согласовыва' / 'соглас'
--     утверждать/утверждается    -> 'утвержда'    / 'утвержда'   (совпало)
--     подписывать/подписывается  -> 'подписыва'   / 'подписыва'  (совпало)
--     направлять/направляется    -> 'направля'    / 'направля'   (совпало)
--     запрашивать/запрашивается  -> 'запрашива'   / 'запрашива'  (совпало)
--
-- То есть разрыв есть у «подавать» и «согласовывать», у остальных совпало.
-- Добавляем только те пары, где расхождение подтверждено замером: лишние
-- варианты раздувают OR-группы и добавляют шум.
--
-- ВАЖНО ПРО ФОРМУ. Только ОДНОСЛОВНЫЕ варианты: to_tsquery не принимает
-- строки с пробелом (проверено, падало с syntax error на 006).
--
-- RAM: +6 строк. Стоимость: 0.1-0.3 мс на запрос.
-- ============================================================================

INSERT INTO term_synonyms (term, expand) VALUES
    -- «подавать» / «подаётся» / «подаёт» — одна мысль, разные леммы.
    ('подавать', ARRAY['подавать', 'подаётся', 'подается', 'подаёт',
                       'подает', 'подать', 'подача']),
    -- «согласовывать» / «согласуется» — тоже расходятся.
    ('согласовывать', ARRAY['согласовывать', 'согласуется',
                            'согласовать', 'согласование', 'согласуют'])
ON CONFLICT (term) DO UPDATE SET expand = EXCLUDED.expand;

-- ----------------------------------------------------------------------------
-- Проверка: варианты однословные, tsquery собирается, расхождение закрыто.
-- ----------------------------------------------------------------------------
DO $$
DECLARE
    bad INT;
    q tsquery;
BEGIN
    SELECT count(*) INTO bad
    FROM term_synonyms s, unnest(s.expand) AS v
    WHERE v LIKE '% %';
    IF bad > 0 THEN
        RAISE EXCEPTION 'вариантов с пробелом: % — to_tsquery упадёт', bad;
    END IF;

    q := kb_tsquery(ARRAY['подавать']);
    RAISE NOTICE 'подавать -> %', q;
END $$;

COMMENT ON TABLE term_synonyms IS
    'Словарь расширения запроса. 006 — аббревиатуры корпуса. 007 — обиходные '
    'пары из глоссария. 009 — глагольные формы, которые лемматизатор не сводит '
    '(подавать/подаётся). Только ОДНОСЛОВНЫЕ варианты: to_tsquery не принимает '
    'строки с пробелом.';