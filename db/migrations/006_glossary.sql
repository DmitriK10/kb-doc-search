-- ============================================================================
-- 006_glossary.sql — расширение запроса аббревиатурами реальных регламентов
--
-- ЗАЧЕМ. Сотрудники спрашивают «кто назначает РП» или «кто такой проджект
-- менеджер», а в регламентах написано «Руководитель проекта» / «РП».
-- Без расширения такие вопросы не находят ответа: FTS ищет по лексемам,
-- а «проджект» и «руководитель» — разные лексемы.
--
-- Бриф (глоссарий от заказчика): «для вашего понимания». Поэтому глоссарий
-- НЕ кладётся в корпус как документ: он не регламент, и цитировать его как
-- источник было бы подменой. Он живёт только как словарь расширения.
--
-- ЧАСТОТЫ по 4 реальным регламентам (169 тыс. символов):
--   РП 273, SS 161, АМ 114, ТКП 72, ПА 71, TPS 49, ГИП 45, CRM 41,
--   ПО 35, ТЗ 21, ЦК 18, TSS 15, ИБ 13, BDM 12, РТЗ 10, УПД 10,
--   АП 9, ПМИ 9, ПСИ 9, ЗнП 9, SLA 7.
-- Берём только реально встречающиеся: редкие дают ноль пользы.
--
-- ВАЖНО — ПОЧЕМУ ВАРИАНТЫ УЗКИЕ. Первая версия словаря включала общие
-- слова-спутники («менеджер», «проектн», «система», «документ»). Проверка
-- показала: tsquery вида
--   'назнача' & ('рп' | 'руководител' | 'проектн' | 'менеджер')
-- матчится на любой пункт про менеджеров и проекты — это шум, который
-- RRF не отфильтрует, потому что FTS-ветка засоряется до слияния.
-- Поэтому вариант добавляется ТОЛЬКО если он однозначно обозначает то же
-- понятие. «РП» -> «руководител», но НЕ «менеджер»; «АМ» -> «аккаунт»,
-- но НЕ «менеджер».
--
-- ВАЖНО ПРО ФОРМУ ВАРИАНТОВ. Только ОДНОСЛОВНЫЕ варианты.
-- Причина (дефект при применении): to_tsquery('russian', ...) падает с
-- «syntax error in tsquery» на строке с пробелом, а kb_lemma многословную
-- строку не лемматизирует. Многословные фразы («проджект менеджер» ->
-- «руководитель проекта») обрабатываются в Python до токенизации,
-- в app/search/glossary.py.
--
-- RAM: ~30 строк. Стоимость: 0.1–0.3 мс на запрос.
-- ============================================================================

INSERT INTO term_synonyms (term, expand) VALUES
    -- Роли. Вариант — только однозначный синоним понятия.
    ('рп',  ARRAY['рп', 'руководител']),
    ('ss',  ARRAY['ss', 'продаже']),
    ('ам',  ARRAY['ам', 'аккаунт']),
    ('па',  ARRAY['па', 'пресейл', 'архитектор']),
    ('гип', ARRAY['гип', 'инженер']),
    ('ап',  ARRAY['ап', 'администратор']),
    ('tps', ARRAY['tps', 'пресейл', 'tss']),

    -- Документы и артефакты.
    ('ткп', ARRAY['ткп', 'коммерческое', 'технико']),
    ('тз',  ARRAY['тз', 'задание']),
    ('знп', ARRAY['знп', 'заявка', 'заявки', 'заявку']),
    ('ртз', ARRAY['ртз', 'трудозатрат', 'трудозатраты']),
    ('упд', ARRAY['упд', 'передаточный']),
    ('пми', ARRAY['пми', 'испытаний']),
    ('пси', ARRAY['пси', 'приёмо', 'приемо']),
    ('кс-2', ARRAY['кс-2', 'кс2']),
    ('кс-3', ARRAY['кс-3', 'кс3']),

    -- Подразделения и системы.
    ('цк',  ARRAY['цк', 'компетенций']),
    ('иб',  ARRAY['иб', 'безопасность']),
    ('crm', ARRAY['crm', 'учётная', 'учетная']),
    ('sla', ARRAY['sla', 'обслуживания']),
    ('bdm', ARRAY['bdm', 'развитию']),

    -- Термины из регламентов.
    ('хардоффер', ARRAY['хардоффер', 'хард', 'оффер']),
    ('пресейл', ARRAY['пресейл', 'presale', 'предпродажа']),
    ('дисквалификация', ARRAY['дисквалификация', 'дисквалифицировать',
                              'дисквалифицирует']),
    ('эскалация', ARRAY['эскалация', 'эскалируется', 'эскалировать'])
ON CONFLICT (term) DO UPDATE SET expand = EXCLUDED.expand;

-- ----------------------------------------------------------------------------
-- Проверка: варианты однословные, tsquery собирается, группа не раздута.
-- ----------------------------------------------------------------------------
DO $$
DECLARE
    n INT;
    bad INT;
    widest INT;
    q tsquery;
BEGIN
    SELECT count(*) INTO n FROM term_synonyms;
    RAISE NOTICE 'терминов в словаре: %', n;

    -- Ни одного варианта с пробелом: иначе to_tsquery упадёт.
    SELECT count(*) INTO bad
    FROM term_synonyms s, unnest(s.expand) AS v
    WHERE v LIKE '% %';
    IF bad > 0 THEN
        RAISE EXCEPTION 'вариантов с пробелом: % — to_tsquery упадёт', bad;
    END IF;

    -- Самая широкая OR-группа. Больше 4 вариантов — повод пересмотреть:
    -- каждый лишний вариант расширяет выдачу и добавляет шум.
    SELECT max(cardinality(expand)) INTO widest FROM term_synonyms;
    RAISE NOTICE 'максимум вариантов в группе: %', widest;

    q := kb_tsquery(ARRAY['назначает', 'рп']);
    RAISE NOTICE 'tsquery для «назначает рп»: %', q;
END $$;

COMMENT ON TABLE term_synonyms IS
    'Словарь расширения запроса. Аббревиатуры из реальных регламентов '
    'добавлены миграцией 006. Только ОДНОСЛОВНЫЕ и только однозначные '
    'варианты: общие слова («менеджер», «документ») засоряют FTS до '
    'слияния, и RRF их не отфильтрует. Глоссарий НЕ является документом '
    'корпуса: он не цитируется как источник, только расширяет запрос.';